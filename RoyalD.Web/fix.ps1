foreach ($f in $files) {
    if (Test-Path $f) {
        $content = Get-Content $f -Raw -Encoding UTF8
        $changed = $false
        foreach ($key in $replacements.Keys) {
            if ($content.Contains($key)) {
                $content = $content.Replace($key, $replacements[$key])
                $changed = $true
            }
        }
        if ($changed) {
            Set-Content $f -Value $content -Encoding UTF8 -NoNewline
            Write-Host "Fixed: $f"
        }
    }
}
